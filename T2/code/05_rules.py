GROUP_DEFAULT = {"01": 1, "02": 1, "03": 2, "04": 1, "05": 1, "06": 1, "07": 1, "08": 1, "09": 1,
                 "11": 1, "12": 2, "13": 1, "15": 1, "16": 1, "17": 1, "18": 1, "19": 2, "20": 4,
                 "21": 1, "22": 3}


def classify(code, name, kg):
    brand = bool(re.match(r"^[^,]+,\S", name)) and code[0] in "245689"
    kw = re.sub(r"\([^()]*\)$", "", name) if brand else name  # 제조사명 속 단어(예: 칠성음료)로 오분류 방지
    for pat, nova, unc, rule in RULES:
        if re.search(pat, kw):
            return nova, unc, rule, int(brand)
    if code.startswith("17"):
        # 17xxx: 조리가공식품 코드군(탕·죽·볶음 등) — 외식/레토르트 구분 불가
        return 3, 1, "C17_조리식품(판단 애매)", int(brand)
    if brand:
        # 제품 코드인데 키워드가 없으면 식품군 기본값을 쓰되 애매 표시
        g = GROUP_DEFAULT.get(kg, 3)
        return (g if g in (1, 2) else 4), 1, "B_제품코드_키워드없음", 1
    return GROUP_DEFAULT.get(kg, 3), 0, f"G_식품군기본({kg})", 0



def main():
    C.ensure_dirs()
    t = pd.read_csv(C.RESULTS_DIR / "foodcode_list.csv", dtype={"N_FCODE": str, "식품군코드": str},
                    encoding="utf-8-sig")
    rows = []
    for r in t.itertuples():
        nova, unc, rule, brand = classify(r.N_FCODE, r.식품명, r.식품군코드)
        rows.append({"N_FCODE": r.N_FCODE, "pred": nova, "uncertain": unc, "rule": rule})
    pr = pd.DataFrame(rows)
    pr.to_csv(C.PRED_DIR / "pred_RULE.csv", index=False, encoding="utf-8-sig")
    print("RULE 예측 분포:", pr.pred.value_counts().sort_index().to_dict())
    ov_path = os.environ.get("T2_RULE_OVERRIDES")
    if ov_path:
        spec = importlib.util.spec_from_file_location("ov", ov_path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        pr2 = pr.copy()
        for code, (n, u, why) in mod.OVERRIDES.items():
            pr2.loc[pr2.N_FCODE == code, ["pred", "uncertain", "rule"]] = [n, u, f"override: {why}"]
        pr2.to_csv(C.PRED_DIR / "pred_RULE_REVIEW.csv", index=False, encoding="utf-8-sig")
        print(f"덮어쓰기 {len(mod.OVERRIDES)}개 적용 → pred_RULE_REVIEW.csv")


if __name__ == "__main__":
    main()
