def strip_counts(s):
    """'신라면(209) / 진라면(148)' → '신라면, 진라면'"""
    if not isinstance(s, str) or not s.strip():
        return ""
    return ", ".join(re.sub(r"\(\d+\)$", "", v.strip()) for v in s.split(" / "))


def describe(row):
    """분류기 공통 입력 문자열 (코드 사전 정보만)."""
    prod = strip_counts(row.get("대표_제품명")) or "없음"
    mfr = strip_counts(row.get("대표_제조사")) or "없음"
    return (f"식품명: {row['식품명']}\n식품군: {row['식품군명']}\n"
            f"대표 제품명: {prod}\n대표 제조사: {mfr}")


def user_msg(row):
    return describe(row) + "\nNOVA 군:"


def build_messages(row, fewshot_rows=None):
    msgs = [{"role": "system", "content": SYSTEM}]
    for ex_row, lab in (fewshot_rows or []):
        msgs.append({"role": "user", "content": user_msg(ex_row)})
        msgs.append({"role": "assistant", "content": str(lab)})
    msgs.append({"role": "user", "content": user_msg(row)})
    return msgs
